// Распознавание записей о тяжёлом состоянии. Намеренно БЕЗ AI: правило должно работать
// предсказуемо, мгновенно, без внешних сервисов (такой текст не стоит отправлять во внешнюю
// модель только затем, чтобы понять, что он тяжёлый) и не зависеть от лимитов бесплатных тарифов.
//
// Цена ошибок несимметрична: лишнее срабатывание — это одна мягкая карточка с поддержкой,
// пропуск — человек в беде получает ответ как на обычную запись. Поэтому список шире, чем
// только прямые формулировки, но не настолько, чтобы реагировать на любую грусть.
//
// Это не диагностика и не оценка риска, а только повод показать человеку, что есть куда
// обратиться, и не обрабатывать такую запись как список дел.

const CRISIS_PATTERNS: RegExp[] = [
  /не хочу (больше )?жить/,
  /не хочется (больше )?жить/,
  /(?<!не )хочу умереть/,
  /(?<!не )хочу умирать/,
  /(по)?кончить с собой/,
  /покончу с собой/,
  /суицид/,
  /самоубийств/,
  /убить себя/,
  /убью себя/,
  /наложить на себя руки/,
  /лучше бы (меня|я) (не было|не родил)/,
  /не вижу смысла жить/,
  /(причинить|нанести|сделать) себе (вред|боль)/,
  /навредить себе/,
  /порезать себя/,
  /хочу исчезнуть навсегда/,
];

function normalize(text: string): string {
  return text.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ");
}

export function detectCrisis(text: string): boolean {
  const t = normalize(text);
  return CRISIS_PATTERNS.some((re) => re.test(t));
}

export interface SupportResource {
  label: string;
  contact: string;
}

const UKRAINE_TIMEZONES = new Set(["Europe/Kyiv", "Europe/Kiev", "Europe/Uzhgorod", "Europe/Zaporozhye"]);

// Контакты зависят от страны, а страну приложение знает только по часовому поясу — это грубо.
// Поэтому для Украины даны конкретные номера, а для остальных — честная общая подсказка вместо
// номера, который мог бы оказаться чужим или несуществующим.
export function supportResourcesForTimezone(timezone: string): SupportResource[] {
  if (UKRAINE_TIMEZONES.has(timezone)) {
    return [
      { label: "Лайфлайн Украина — бесплатная линия поддержки", contact: "7333" },
      { label: "Экстренная помощь, если опасность прямо сейчас", contact: "112" },
    ];
  }
  return [
    { label: "Экстренная служба в твоей стране, если опасность прямо сейчас", contact: "номер экстренной помощи" },
    { label: "Линия доверия или кризисная служба", contact: "найди номер для своей страны" },
  ];
}

// Текст поддержки для чата с ботом (в приложении тот же смысл показывает карточка «Я рядом»).
export function supportMessageText(resources: SupportResource[]): string {
  return (
    "Записал. То, что ты написал, звучит тяжело, и это важно. Я не стал разбирать запись на задачи.\n\n" +
    "Если можешь, расскажи о том, как тебе сейчас, кому-то из близких. Ты не обязан справляться один.\n\n" +
    resources.map((r) => `${r.label}: ${r.contact}`).join("\n") +
    "\n\nЯ бот, а не специалист, и помочь так, как может живой человек, не могу."
  );
}
