// Заглушка базы для модульных тестов: чистые функции базу не трогают, а настоящий клиент Prisma требует отдельной генерации.
// Если тест всё же обратится к базе, он упадёт с понятным сообщением вместо тихой ошибки.
export const prisma: any = new Proxy(
  {},
  {
    get(_t, name) {
      throw new Error(`Модульный тест обратился к базе (prisma.${String(name)}). Вынеси логику в чистую функцию или подмени prisma в самом тесте.`);
    },
  }
);
